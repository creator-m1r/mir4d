// MirEngine/IO/Importer.h
// =================================================================================
// Абстрактный интерфейс для загрузки CAD-моделей.
//
// Все импортёры возвращают корневой узел сцены, заполненный дочерними узлами
// и геометрией. Конкретная реализация скрывает работу с конкретной библиотекой
// (Assimp, OpenCASCADE, собственная загрузка STL и т.д.).
//
// Архитектура:
//   - Модуль IO не зависит от рендеринга и платформы.
//   - Возвращает готовый Node с прикреплёнными Mesh.
//   - Внешний код может добавить полученный узел в основную сцену.
//
// Использование:
//   auto importer = std::make_unique<AssimpImporter>();
//   auto rootNode = importer->load("model.step");
//   if (rootNode) scene->addNode(std::move(rootNode));
// =================================================================================

#pragma once

#include <memory>
#include <string>

namespace MirEngine {

class Node;

class Importer {
public:
    virtual ~Importer() = default;

    // --------------------------------------------------------------------------
    // Загружает файл и возвращает корневой узел с геометрией.
    // Возвращает nullptr в случае ошибки.
    // --------------------------------------------------------------------------
    virtual std::unique_ptr<Node> load(const std::string& filePath) = 0;
};

} // namespace MirEngine