// MirEngine/Core/Events/EventType.hpp
// 🏷️ Перечень всех стандартных типов событий в MirEngine.
//
// EventType — это перечисление, которое определяет, КАКОГО РОДА событие
// произошло в движке. В отличие от класса конкретного события (например,
// EntityCreated), которое несёт подробные данные (ID созданной сущности),
// EventType — это просто метка категории.
//
// Зачем это нужно?
//   • Подписчик может фильтровать события не по точному классу, а по категории.
//   • Можно быстро посмотреть, какие вообще бывают события, в одном месте.
//   • Упрощает сериализацию и журналирование.
//
// Категории событий:
//   • Document   — создание, открытие, закрытие документа.
//   • Object     — добавление, удаление, изменение объекта в документе.
//   • Entity     — создание, удаление сущности в сцене.
//   • Scene      — изменение структуры сцены, камеры.
//   • Selection  — изменение выделения объектов.
//   • Feature    — добавление, редактирование, подавление конструктивного элемента.
//   • Tool       — смена активного инструмента.
//   • View       — изменение параметров отображения (зум, панорамирование).
//
// В будущем этот список будет расти, но благодаря единому перечислению
// мы всегда знаем, где искать все возможные события.
//
// Чистый C++23, без внешних зависимостей.

#pragma once

#include <cstdint>   // для uint32_t

namespace mir {

enum class EventType : uint32_t {
    // ── Документ ─────────────────────────────────────────────
    DocumentCreated,         // создан новый документ
    DocumentOpened,          // открыт существующий документ
    DocumentClosed,          // документ закрыт
    DocumentModified,        // документ изменён (сохранение?)

    // ── Объекты документа ────────────────────────────────────
    ObjectAdded,             // объект добавлен в документ
    ObjectRemoved,           // объект удалён из документа
    ObjectChanged,           // свойства объекта изменены

    // ── Сущности сцены ───────────────────────────────────────
    EntityCreated,           // создана новая сущность в сцене
    EntityDestroyed,         // сущность удалена из сцены
    EntityMoved,             // сущность перемещена
    EntityTransformed,       // трансформация сущности изменена (позиция, поворот, масштаб)

    // ── Сцена ─────────────────────────────────────────────────
    SceneChanged,            // общее изменение сцены (перестроение)
    SceneCleared,            // сцена очищена (все сущности удалены)

    // ── Выделение ─────────────────────────────────────────────
    SelectionChanged,        // изменился набор выделенных объектов/сущностей

    // ── Конструктивные элементы (Feature) ────────────────────
    FeatureAdded,            // добавлен новый конструктивный элемент
    FeatureRemoved,          // конструктивный элемент удалён
    FeatureModified,         // параметры конструктивного элемента изменены

    // ── Инструменты ───────────────────────────────────────────
    ToolChanged,             // активный инструмент изменён

    // ── Отображение ───────────────────────────────────────────
    ViewChanged,             // параметры вида изменены (зум, панорама, угол)
    CameraChanged,           // камера перемещена или повёрнута

    // ── Жизненный цикл движка ─────────────────────────────────
    EngineInitialized,       // движок инициализирован
    EngineShutdown,          // движок завершает работу

    // ── Прочее ─────────────────────────────────────────────────
    Unknown                  // неизвестный тип события (заглушка для расширения)
};

} // namespace mir