// MirEngine/Core/Events/Event.hpp
// 📡 Базовое событие в MirEngine — основа для всей событийной системы.
//
// В большом движке компоненты должны общаться друг с другом, но при этом
// не зависеть друг от друга напрямую. Например, когда пользователь создаёт
// новую деталь, об этом нужно узнать и панели инструментов, и дереву проекта,
// и 3D-виду. Если каждый будет напрямую вызывать методы другого, получится
// «спагетти» из зависимостей, которое невозможно поддерживать.
//
// Событийная система решает эту проблему через паттерн «издатель-подписчик»:
//   • Один компонент публикует событие (например, EntityCreated).
//   • Другие компоненты, которым это интересно, подписываются и получают уведомление.
//   • Издатель не знает, кто подписан, а подписчики не знают, кто издатель.
//   • Все общаются только через Event и EventBus (будет создан позже).
//
// Event — это базовый класс для всех событий. Каждое конкретное событие
// (создание сущности, изменение свойства, завершение операции…) будет
// наследоваться от Event и добавлять свои поля.
//
// Прямо сейчас Event содержит только флаг handled — он показывает, было ли
// событие уже обработано. Если handled = true, EventBus может прекратить
// рассылку этого события дальше (как «съеденный» клик мыши).
//
// Чистый C++23, без внешних зависимостей.

#pragma once

namespace mir {

// ── Базовый класс события ────────────────────────────────────
class Event {
public:
    // Виртуальный деструктор — обязателен для полиморфных классов.
    // Он позволяет корректно удалять наследников через указатель на Event.
    virtual ~Event() = default;

    // ── Флаг «обработано» ─────────────────────────────────────
    // Если подписчик установил handled = true, EventBus может перестать
    // рассылать это событие дальше. Это как «я съел пирожок, другим не достанется».
    void setHandled(bool value) noexcept { m_handled = value; }
    [[nodiscard]] bool isHandled() const noexcept { return m_handled; }

private:
    bool m_handled = false;
};

} // namespace mir