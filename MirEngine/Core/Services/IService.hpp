// MirEngine/Core/Services/IService.hpp
// 🏗️ Базовый интерфейс для всех сервисов в MirEngine.
//
// В MirEngine вся логика организована в виде сервисов — независимых модулей,
// каждый из которых отвечает за свою область: геометрия, документы, сцена,
// выделение, рендеринг. Сервисы не создаются хаотично, а регистрируются
// в ServiceRegistry (будет создан позже), который управляет их жизненным
// циклом: созданием, инициализацией и завершением работы.
//
// IService — это общий интерфейс для всех сервисов. Он требует от каждого
// сервиса реализовать четыре метода:
//   • initialize()  — настройка и выделение ресурсов.
//   • shutdown()    — освобождение ресурсов.
//   • isReady()     — можно ли пользоваться сервисом прямо сейчас.
//   • name()        — человекочитаемое имя (для логов и отладки).
//
// Благодаря единому интерфейсу движок может управлять всеми сервисами
// одинаково: запустить их в нужном порядке, корректно завершить работу,
// запросить состояние. А если сервис не готов, движок не даст его
// использовать, предотвращая ошибки.
//
// Пример конкретного сервиса:
//   class GeometryService : public IService {
//       Result<void> initialize() override { ... }
//       void shutdown() override { ... }
//       bool isReady() const noexcept override { return m_ready; }
//       std::string name() const override { return "GeometryService"; }
//   };
//
// Чистый C++23, без внешних зависимостей.

#pragma once

#include "../Result/Result.hpp"   // Result<void>, ErrorCode
#include <string>                 // std::string

namespace mir {

class IService {
public:
    virtual ~IService() = default;

    // ── Инициализация ────────────────────────────────────────
    // Выделяет ресурсы и готовит сервис к работе.
    // Должен быть вызван до любого другого метода.
    // Возвращает успех или ошибку с описанием, если инициализация не удалась.
    virtual Result<void> initialize() = 0;

    // ── Завершение работы ────────────────────────────────────
    // Освобождает все ресурсы, занятые сервисом.
    // После вызова shutdown() сервис больше не должен использоваться
    // до повторного вызова initialize().
    virtual void shutdown() = 0;

    // ── Проверка готовности ──────────────────────────────────
    // Возвращает true, если сервис был успешно инициализирован
    // и готов к использованию. Если false, вызывать другие методы нельзя.
    [[nodiscard]] virtual bool isReady() const noexcept = 0;

    // ── Имя сервиса ──────────────────────────────────────────
    // Человекочитаемое имя для логов, отладки и диагностики.
    // Например: "GeometryService", "SceneService", "SelectionService".
    [[nodiscard]] virtual std::string name() const = 0;
};

} // namespace mir