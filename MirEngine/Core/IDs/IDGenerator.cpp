// ─────────────────────────────────────────────────────────────
// 📁 MirEngine/Core/IDs/IDGenerator.cpp
// ─────────────────────────────────────────────────────────────
// 🏭 Реализация генератора уникальных идентификаторов.
//
// В нашем проекте МИР 4D мы имеем дело с огромным количеством
// объектов: детали, компоненты, чертежи, эскизы, документы...
// Чтобы никогда не перепутать Деталь №1 с Документом №1,
// мы используем разные «счётчики» для каждого типа объектов.
//
// Класс IDGenerator содержит внутри себя несколько таких
// счётчиков — по одному на каждый тип идентификатора:
//   • EntityID   — для сущностей (детали, камеры, лампы)
//   • ObjectID   — для объектов документа (тела, эскизы)
//   • ComponentID — для компонентов в сборках
//   • FeatureID  — для операций моделирования (выдавливание и т.д.)
//   • DocumentID — для документов (файлов проекта)
//   • ProjectID  — для проектов верхнего уровня
//
// Каждый счётчик атомарный — это значит, что даже если два
// разных «работника» (потока) одновременно попросят новый номер,
// они не перепутаются и не получат одинаковый номер.
//
// 🔧 Почему файл почти пустой?
// Потому что вся логика уже реализована прямо в заголовочном
// файле IDGenerator.hpp. Такое решение принято для максимальной
// производительности: компилятор видит весь код и может
// встроить (inline) короткие функции, делая программу быстрее.
//
// Но .cpp‑файл всё равно нужен — он «регистрирует» заголовок
// и гарантирует, что код будет скомпилирован ровно один раз.
// Кроме того, здесь мы будем хранить более сложные методы,
// если они появятся в будущем (например, сохранение/загрузка
// состояния счётчиков из файла).
//
// Чистый C++23, без внешних зависимостей.
// ─────────────────────────────────────────────────────────────

// Подключаем наш заголовочный файл, чтобы компилятор знал,
// что мы реализуем именно этот класс.
