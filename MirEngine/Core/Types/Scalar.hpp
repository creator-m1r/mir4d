// MirEngine/Core/Types/Scalar.hpp
// 🔢 Единый числовой тип для всего инженерного ядра MirEngine.
//
// В огромных проектах часто встречается путаница: где-то используют float,
// где-то double, где-то CGFloat. Это приводит к ошибкам точности и проблемам
// при стыковке разных модулей. В MirEngine мы решаем эту проблему раз и
// навсегда: ВЕСЬ движок использует один-единственный тип — `mir::Scalar`.
//
// Сейчас `Scalar` — это просто `double` (число двойной точности).
// double обеспечивает около 15-16 десятичных знаков точности, что идеально
// подходит для инженерных расчётов, где важна каждая сотая миллиметра.
//
// Почему это важно:
//   • Все координаты, расстояния, углы и размеры хранятся в Scalar.
//   • Все математические операции (векторы, матрицы, кватернионы) используют Scalar.
//   • Если в будущем мы захотим перейти на float (например, для игр) или
//     на long double (для сверхточных научных расчётов), достаточно изменить
//     только эту одну строчку.
//
// Использование:
//   mir::Scalar length = 100.5;     // длина 100.5 миллиметров
//   mir::Scalar angle = mir::pi;    // угол в радианах
//   mir::Scalar epsilon = 1e-10;    // допуск для сравнения
//
// Чистый C++23, без внешних зависимостей.

#pragma once

namespace mir {

// Главный числовой тип MirEngine.
// double выбран по умолчанию для инженерной точности.
using Scalar = double;

} // namespace mir