// MirEngine/Core/Engine/EngineState.hpp
// 📊 Состояния жизненного цикла движка MirEngine.
//
// Движок проходит через строго определённые стадии:
//
//   Created       → объект только что создан (конструктор отработал).
//                   Ресурсы ещё не выделены.
//
//   Initializing  → идёт процесс initialize() (настройка логгера,
//                   загрузка конфигурации, подготовка подсистем).
//
//   Ready         → инициализация успешно завершена.
//                   Движок готов к запуску главного цикла.
//
//   Running       → главный цикл активен, обрабатываются кадры,
//                   команды и события.
//
//   ShuttingDown  → идёт процесс shutdown() (сохранение данных,
//                   выгрузка плагинов, освобождение ресурсов).
//
//   Shutdown      → движок полностью остановлен, все ресурсы освобождены.
//                   Повторный вызов initialize() из этого состояния
//                   в текущей реализации запрещён (можно расширить позже).
//
// Допустимые переходы (контролируются внутри Engine):
//   Created      → Initializing → Ready
//   Ready        → Running
//   Running      → ShuttingDown → Shutdown
//   Ready        → ShuttingDown → Shutdown   (если shutdown вызван без Running)
//
// Любой другой переход считается ошибкой состояния (InvalidState).
//
// Чистый C++23, без внешних зависимостей.

#pragma once

namespace mir {

enum class EngineState {
    Created,        // объект Engine только что создан
    Initializing,   // выполняется initialize()
    Ready,          // инициализация завершена, можно запускать цикл
    Running,        // главный цикл активен
    ShuttingDown,   // выполняется shutdown()
    Shutdown        // движок полностью остановлен
};

} // namespace mir