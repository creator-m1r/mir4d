// MirEngine/Viewport/Viewport.h
// =================================================================================
// Управляющий класс вьюпорта.
//
// Инкапсулирует логику взаимодействия камеры, сцены и рендерера.
// Не зависит от платформы (SwiftUI, WinUI) и не знает о конкретном API рендеринга.
// Предоставляет методы для изменения размеров, запуска рендеринга и установки
// активной камеры/сцены.
//
// Архитектура:
//   MirUI (SwiftUI/WinUI) владеет Viewport и передаёт ему события (изменение размера,
//   запрос кадра, мышь). Viewport, в свою очередь, вызывает методы Renderer и
//   делегирует события мыши контроллеру камеры.
//
// Жизненный цикл:
//   1. Создать Viewport, передав ему Renderer и начальные размеры.
//   2. Установить камеру через setCamera() (автоматически создаётся CameraController).
//   3. При изменении размера вызывать resize().
//   4. Для каждого кадра вызывать render().
//   5. Передавать события мыши через onMouse*() и периодически updateController().
// =================================================================================

#pragma once

#include <cstdint>
#include <memory>

#include "SelectionManager.h"

namespace MirEngine {

// Предварительные объявления
class Camera;
class CameraController;
class Scene;

namespace Rendering {
    class Renderer;
    class RenderContext;
}

class Viewport {
public:
    // --------------------------------------------------------------------------
    // Конструктор.
    // renderer - указатель на конкретный рендерер (OpenGLRenderer и т.п.)
    // width, height - начальные размеры вьюпорта в пикселях.
    // --------------------------------------------------------------------------
    Viewport(Rendering::Renderer* renderer, uint32_t width, uint32_t height);

    // --------------------------------------------------------------------------
    // Устанавливает активную камеру.
    // Камера должна существовать в течение времени использования Viewport.
    // При установке камеры автоматически создаётся контроллер камеры.
    // --------------------------------------------------------------------------
    void setCamera(Camera* camera);

    // --------------------------------------------------------------------------
    // Устанавливает активную сцену для рендеринга.
    // --------------------------------------------------------------------------
    void setScene(Scene* scene);

    // --------------------------------------------------------------------------
    // Основной метод рендеринга одного кадра.
    // Заполняет RenderContext матрицами из камеры, вызывает renderer->render().
    // --------------------------------------------------------------------------
    void render();

    // --------------------------------------------------------------------------
    // Обрабатывает изменение размера области вывода.
    // --------------------------------------------------------------------------
    void resize(uint32_t width, uint32_t height);

    // --------------------------------------------------------------------------
    // Возвращает текущий RenderContext (для доступа к матрицам, размеру и т.д.)
    // --------------------------------------------------------------------------
    Rendering::RenderContext& getContext() { return *m_context; }

    // --------------------------------------------------------------------------
    // Методы для передачи событий мыши от UI.
    // Делегируют вызовы контроллеру камеры, если он существует.
    // --------------------------------------------------------------------------
    void onMouseDown(int button, float x, float y) {
        if (m_cameraController) m_cameraController->onMouseDown(button, x, y);
    }
    void onMouseUp(int button, float x, float y) {
        if (m_cameraController) m_cameraController->onMouseUp(button, x, y);
    }
    void onMouseMove(float x, float y) {
        if (m_cameraController) m_cameraController->onMouseMove(x, y);
    }
    void onMouseScroll(float delta) {
        if (m_cameraController) m_cameraController->onMouseScroll(delta);
    }

    // --------------------------------------------------------------------------
    // Обработка клика мыши для выделения объектов (пикинг).
    // x, y – координаты в пикселях в пределах вьюпорта.
    // addToSelection – если true, добавляет к текущему выделению,
    // иначе заменяет его.
    // --------------------------------------------------------------------------
    void onMouseClick(float x, float y, bool addToSelection = false);

    // --------------------------------------------------------------------------
    // Обновляет контроллер камеры (например, для инерции или анимации).
    // Следует вызывать каждый кадр перед render().
    // --------------------------------------------------------------------------
    void updateController() {
        if (m_cameraController) m_cameraController->update();
    }

private:
    Rendering::Renderer* m_renderer;
    std::unique_ptr<Rendering::RenderContext> m_context;
    Camera* m_camera = nullptr;
    Scene*  m_scene  = nullptr;

    // Контроллер камеры, владеет логикой вращения/перемещения/зума.
    // Создаётся при вызове setCamera(), уничтожается при сбросе камеры.
    std::unique_ptr<CameraController> m_cameraController;

    // Менеджер выделения объектов. Инициализируется в конструкторе.
    std::unique_ptr<SelectionManager> m_selectionManager;
};

} // namespace MirEngine