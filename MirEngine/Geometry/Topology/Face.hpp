// Face — это ключевой элемент граничного представления (B-Rep). Грань
// представляет собой ограниченную часть поверхности, заданную замкнутым
// контуром (Wire) из одного или нескольких рёбер. Все грани вместе
// образуют поверхность твёрдого тела (Body).
//
// Основные свойства:
//   • edges        — индексы рёбер, образующих внешний контур грани.
//   • surface      — опциональная поверхность, задающая точную геометрию грани.
//   • normal       — направление "наружу" от тела (перпендикуляр к грани).
//   • innerLoops   — внутренние контуры (отверстия в грани).
//
// Face используется в:
//   • Body (B-Rep) — как составная часть твёрдого тела.
//   • Булевых операциях — грани пересекаются, разрезаются и объединяются.
