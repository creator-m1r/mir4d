#pragma once

#include <vector>

#include "../Core/Identity/TypedID.hpp"

namespace mir
{

class Face
{
public:

    Face() = default;

    explicit Face(FaceID id)
        : m_id(id)
    {
    }

    FaceID id() const noexcept
    {
        return m_id;
    }

    const std::vector<LoopID>& loops() const noexcept
    {
        return m_loops;
    }

    void addLoop(LoopID id)
    {
        m_loops.push_back(id);
    }

    bool isReversed() const noexcept
    {
        return m_reversed;
    }

    void setReversed(bool value) noexcept
    {
        m_reversed = value;
    }

private:

    FaceID m_id;

    std::vector<LoopID> m_loops;

    // Пока просто ID.
    // Позже сюда добавим SurfaceID.
    std::uint64_t m_surfaceID = 0;

    bool m_reversed = false;
};

}