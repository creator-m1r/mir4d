// ─────────────────────────────────────────────────────────────
//  MirEngine/Geometry/Core/GeometryObject.hpp
// ─────────────────────────────────────────────────────────────
//  ГЕОМЕТРИЧЕСКИЙ ОБЪЕКТ — «кирпичик» любой 3D-сцены
//
// В системе МИР 4D каждая точка, линия, окружность, тело,
// поверхность или деталь является GeometryObject.
// У каждого такого объекта есть:
//   • Уникальный идентификатор (id) — чтобы его можно было найти
//     в большой картотеке GeometryContext.
//   • Трансформация (transform) — положение в пространстве,
//     поворот и масштаб. Это как «паспорт» с адресом прописки:
//     где именно находится объект и как он повёрнут.
//
// Сам по себе GeometryObject — это просто контейнер для базовых
// свойств, который наследуется более конкретными типами:
//   Point  → наследует GeometryObject (становится точкой в 3D)
//   Line   → наследует GeometryObject (становится линией)
//   Solid  → наследует GeometryObject (становится твёрдым телом)
//   и так далее…
//
// Это позволяет GeometryContext хранить ВСЕ типы объектов в одном
// списке, не задумываясь, кто именно перед ним: точка или тело.
//
// Чистый C++23, без внешних зависимостей.
// ─────────────────────────────────────────────────────────────

#pragma once

#include "GeometryID.hpp"       // наш уникальный идентификатор
#include <string>               // для имени объекта (name)

namespace M1R {

// ╔══════════════════════════════════════════════════════════╗
// ║  Класс Transform — положение, поворот, масштаб          ║
// ║  (заглушка; реальная версия в Math/Transform.hpp)       ║
// ╚══════════════════════════════════════════════════════════╝
struct Transform {
    double position[3] = {0.0, 0.0, 0.0};   // x, y, z (метры)
    double rotation[4] = {0.0, 0.0, 0.0, 1.0}; // кватернион (x,y,z,w)
    double scale[3]    = {1.0, 1.0, 1.0};   // масштаб по осям

    // Создать «пустую» трансформацию (объект в начале координат, не повёрнут, не масштабирован)
    static Transform identity() {
        return Transform{};
    }
};

// ╔══════════════════════════════════════════════════════════╗
// ║  Главный класс: GeometryObject                          ║
// ╚══════════════════════════════════════════════════════════╝
class GeometryObject {
public:
    // ── Уникальный номер (паспорт) ──────────────────────────
    GeometryID id;

    // ── Положение в пространстве ─────────────────────────────
    Transform transform;

    // ── Человекочитаемое имя (например, «Колесо», «Стена») ──
    std::string name = "Unnamed";

    // ── Конструкторы ─────────────────────────────────────────
    // Создать безымянный объект с нулевым ID и начальной трансформацией
    GeometryObject() noexcept
        : id(0)
        , transform(Transform::identity())
        , name("Unnamed") {}

    // Создать объект с заданным именем и ID
    GeometryObject(GeometryID id_, const std::string& name_ = "Unnamed")
        : id(id_)
        , transform(Transform::identity())
        , name(name_) {}

    // Виртуальный деструктор — обязателен для классов-родителей,
    // чтобы при удалении наследников всё чистилось правильно
    virtual ~GeometryObject() = default;

    // ── Сравнение объектов ──────────────────────────────────
    // Два объекта равны, если у них одинаковый ID
    bool operator==(const GeometryObject& other) const noexcept {
        return id == other.id;
    }
    bool operator!=(const GeometryObject& other) const noexcept {
        return !(*this == other);
    }

    // ── Получить тип объекта строкой (для отладки) ──────────
    // Наследники могут переопределить этот метод.
    // Например, класс Point переопределит его, чтобы возвращать "Point".
    virtual const char* typeName() const noexcept {
        return "GeometryObject";
    }
};

} // namespace M1R