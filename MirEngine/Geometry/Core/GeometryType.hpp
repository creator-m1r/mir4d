// 🏷️ ПЕРЕЧИСЛЕНИЕ ТИПОВ ГЕОМЕТРИЧЕСКИХ ОБЪЕКТОВ (GeometryType)
//
// В системе МИР 4D геометрические объекты бывают разных видов:
// точки, линии, окружности, поверхности, тела, сетки и так далее.
// Чтобы программа могла быстро понять, с чем она имеет дело,
// используется это перечисление.
//
// Представь, что у тебя есть завод, где производят разные детали:
//   • Винты (Point)      — самые простые, одна точка.
//   • Проволока (Edge)   — линия между двумя точками.
//   • Листы металла (Face) — плоская или кривая поверхность.
//   • Готовые детали (Solid) — объёмное тело, как кубик или шар.
//
// GeometryType — это ярлычок, который мы наклеиваем на каждую
// деталь. По ярлычку сразу видно, что это: точка или целый
// автомобильный двигатель.
//
// Зачем это нужно?
//   1. Быстрое ветвление: если тип == Circle, значит у объекта
//      есть радиус. Не нужно гадать.
//   2. Фильтрация: выбрать из всего списка только твёрдые тела.
//   3. Сериализация: при сохранении в файл записать тип, чтобы
//      при загрузке создать правильный класс.
//   4. Безопасность: нельзя случайно обработать точку как тело,
//      потому что программа всегда знает точный тип.
//
// Типы упорядочены от простого к сложному:
//   Точка → Кривая → Поверхность → Тело → Сетка → Сборка
//
// Чистый C++23, без внешних зависимостей.
// ─────────────────────────────────────────────────────────────

#pragma once

#include <cstdint>   // для uint8_t (экономия памяти)

namespace M1R {

// ╔══════════════════════════════════════════════════════════╗
// ║  Перечисление всех возможных типов геометрии            ║
// ╚══════════════════════════════════════════════════════════╝
enum class GeometryType : uint8_t {
    // ── Базовые (нульмерные, одномерные) ────────────────────
    Point,         // точка в пространстве (0D)
    Vertex,        // вершина (точка с дополнительной информацией)
    Edge,          // ребро (линия между двумя вершинами)
    Line,          // прямая (бесконечная)
    Arc,           // дуга (часть окружности)
    Circle,        // окружность (замкнутая кривая)

    // ── Кривые (сложные) ────────────────────────────────────
    Curve,         // абстрактная параметрическая кривая
    BezierCurve,   // кривая Безье (гладкая, по контрольным точкам)
    BSplineCurve,  // B-сплайн (ещё более гибкая кривая)

    // ── Поверхности (двумерные) ─────────────────────────────
    Surface,       // абстрактная параметрическая поверхность
    Face,          // грань (ограниченная часть поверхности)
    PlaneSurface,  // плоскость
    CylinderSurface,  // цилиндрическая поверхность
    ConeSurface,      // коническая поверхность
    SphereSurface,    // сферическая поверхность
    TorusSurface,     // тороидальная поверхность (бублик)

    // ── Объёмные тела ──────────────────────────────────────
    Shell,         // оболочка (набор граней, возможно незамкнутая)
    Solid,         // твёрдое тело (замкнутая оболочка с объёмом)

    // ── Полигональная сетка ─────────────────────────────────
    Mesh,          // треугольная сетка (для рендеринга)

    // ── Составные объекты ───────────────────────────────────
    Body,          // тело (может содержать несколько Solid)
    Assembly,      // сборка (несколько деталей)

    // ── Специальные ─────────────────────────────────────────
    Unknown        // неизвестный тип (заглушка на всякий случай)
};

// ─────────────────────────────────────────────────────────────
// 🎨 Вспомогательная функция: превратить тип в читаемую строку
//    (для логов, отладки, вывода в GUI)
// ─────────────────────────────────────────────────────────────
inline const char* geometryTypeToString(GeometryType type) noexcept {
    switch (type) {
        case GeometryType::Point:            return "Point";
        case GeometryType::Vertex:           return "Vertex";
        case GeometryType::Edge:             return "Edge";
        case GeometryType::Line:             return "Line";
        case GeometryType::Arc:              return "Arc";
        case GeometryType::Circle:           return "Circle";
        case GeometryType::Curve:            return "Curve";
        case GeometryType::BezierCurve:      return "BezierCurve";
        case GeometryType::BSplineCurve:     return "BSplineCurve";
        case GeometryType::Surface:          return "Surface";
        case GeometryType::Face:             return "Face";
        case GeometryType::PlaneSurface:     return "PlaneSurface";
        case GeometryType::CylinderSurface:  return "CylinderSurface";
        case GeometryType::ConeSurface:      return "ConeSurface";
        case GeometryType::SphereSurface:    return "SphereSurface";
        case GeometryType::TorusSurface:     return "TorusSurface";
        case GeometryType::Shell:            return "Shell";
        case GeometryType::Solid:            return "Solid";
        case GeometryType::Mesh:             return "Mesh";
        case GeometryType::Body:             return "Body";
        case GeometryType::Assembly:         return "Assembly";
        case GeometryType::Unknown:          return "Unknown";
        default:                             return "???";
    }
}

} // namespace M1R