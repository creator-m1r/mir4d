// MirEngine/Rendering/Resources/ShaderLibrary.h
// =================================================================================
// Библиотека шейдеров.
//
// Управляет жизненным циклом и доступом к шейдерным программам.
// Позволяет загружать шейдеры по имени и исходному коду, кэшировать их,
// а затем получать доступ по дескриптору ShaderHandle (который является строкой-именем).
//
// В будущем можно заменить ShaderHandle на числовой идентификатор, но сейчас
// имя шейдера идеально подходит для быстрого поиска и отладки.
//
// Архитектура:
//   - ShaderLibrary не зависит от конкретного рендерер-бэкенда (OpenGL/Metal).
//   - Она работает с абстрактным Shader и создаёт экземпляры через фабрику,
//     которая будет предоставлена платформенным кодом.
//   - Шейдеры компилируются по требованию (лениво) и хранятся в кэше.
//
// Использование:
//   1. Создать ShaderLibrary, передав фабричную функцию для создания Shader.
//   2. Вызвать load("Simple", vertexSrc, fragmentSrc).
//   3. Позже получить шейдер через get("Simple") и использовать его в Material.
// =================================================================================

#pragma once

#include <string>
#include <unordered_map>
#include <memory>
#include <functional>

namespace MirEngine {
namespace Rendering {

// Предварительное объявление Shader (абстрактный интерфейс)
class Shader;

// ---------------------------------------------------------------------------------
// Дескриптор шейдера — для простоты используем строку (уникальное имя шейдера).
// В будущем можно сменить на uint32_t, но тогда нужно вести маппинг имён.
// ---------------------------------------------------------------------------------
using ShaderHandle = std::string;

// ---------------------------------------------------------------------------------
// Тип фабричной функции, которая создаёт конкретный Shader.
// Платформенный код передаёт её в конструктор библиотеки.
// ---------------------------------------------------------------------------------
using ShaderFactory = std::function<std::shared_ptr<Shader>()>;

// ---------------------------------------------------------------------------------
// ShaderLibrary — кэш шейдеров
// ---------------------------------------------------------------------------------
class ShaderLibrary {
public:
    // --------------------------------------------------------------------------
    // Конструктор.
    // Принимает фабрику, которая умеет создавать пустой Shader (например, OpenGLShader).
    // Это позволяет библиотеке не зависеть от конкретного API.
    // --------------------------------------------------------------------------
    explicit ShaderLibrary(ShaderFactory factory);

    // --------------------------------------------------------------------------
    // Загружает (компилирует) шейдер с заданным именем из исходников GLSL/HLSL.
    // Возвращает дескриптор, который можно использовать для получения шейдера.
    // Если шейдер с таким именем уже существует, возвращает его дескриптор
    // без перекомпиляции (если явно не указано перезаписать).
    // --------------------------------------------------------------------------
    ShaderHandle load(const std::string& name,
                      const std::string& vertexSource,
                      const std::string& fragmentSource,
                      bool forceReload = false);

    // --------------------------------------------------------------------------
    // Возвращает указатель на шейдер по дескриптору.
    // Если шейдер не найден, возвращает nullptr.
    // --------------------------------------------------------------------------
    std::shared_ptr<Shader> get(const ShaderHandle& handle) const;

    // --------------------------------------------------------------------------
    // Проверяет, существует ли шейдер с данным дескриптором.
    // --------------------------------------------------------------------------
    bool contains(const ShaderHandle& handle) const;

    // --------------------------------------------------------------------------
    // Удаляет шейдер из библиотеки (освобождает ресурсы GPU через деструктор).
    // --------------------------------------------------------------------------
    void remove(const ShaderHandle& handle);

    // --------------------------------------------------------------------------
    // Очищает библиотеку полностью.
    // --------------------------------------------------------------------------
    void clear();

private:
    ShaderFactory m_factory;                                  // Фабрика для создания Shader
    std::unordered_map<ShaderHandle, std::shared_ptr<Shader>> m_shaders; // Кэш
};

} // namespace Rendering
} // namespace MirEngine