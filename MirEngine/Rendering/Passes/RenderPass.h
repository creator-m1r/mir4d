// MirEngine/Rendering/Passes/RenderPass.h
// =================================================================================
// Абстрактный интерфейс прохода рендеринга.
//
// Проход (Pass) — это логическая единица рендеринга, отвечающая за определённый
// слой изображения: основная геометрия, сетка, выделение, gizmo, оверлеи.
// Каждый проход получает на вход текущий контекст кадра (RenderContext),
// сцену (Scene) и камеру (Camera), а также имеет доступ к RenderDevice для
// выполнения низкоуровневых команд рисования.
//
// Архитектура:
//   OpenGLRenderer (или другой Renderer) владеет списком проходов.
//   При каждом кадре он последовательно вызывает:
//     1. begin(context)   — подготовка (очистка буфера, если нужно)
//     2. execute(context, scene, camera, device) — основная работа
//     3. end(context)     — завершение (восстановление состояний и т.п.)
//
// Конкретные реализации проходов (GeometryPass, GridPass, SelectionPass...)
// будут находиться в поддиректориях Passes/ и могут использовать специфичные
// ресурсы (шейдеры, буферы), создавая их через RenderDevice.
//
// Правило изоляции:
//   Заголовок RenderPass.h не содержит зависимостей от OpenGL, Metal или Vulkan.
//   Он работает только с абстрактными или легковесными типами MirEngine.
// =================================================================================

#pragma once

namespace MirEngine {

// Предварительные объявления (чтобы минимизировать зависимости)
class Scene;
class Camera;

namespace Rendering {

class RenderContext;
class RenderDevice;

class RenderPass {
public:
    virtual ~RenderPass() = default;

    // --------------------------------------------------------------------------
    // Подготовка к выполнению прохода.
    // Вызывается один раз в начале прохода, перед execute().
    // Может использоваться для очистки временных буферов, установки
    // глобальных состояний, привязки Framebuffer и т.п.
    // Передача RenderDevice опциональна (если нужна для подготовки).
    // --------------------------------------------------------------------------
    virtual void begin(RenderContext& context, RenderDevice* device = nullptr) {
        // По умолчанию ничего не делает
        (void)context;
        (void)device;
    }

    // --------------------------------------------------------------------------
    // Основной метод выполнения прохода.
    // Вызывается после begin(). Здесь происходит всё рисование, связанное с данным
    // проходом: перебор объектов сцены, формирование RenderCommand, вызов device->draw().
    //
    // Аргументы:
    //   context  — данные текущего кадра (матрицы, размеры, время)
    //   scene    — сцена для рендеринга (содержит узлы, геометрию)
    //   camera   — активная камера (может понадобиться для специфических проходов,
    //              хотя основные матрицы уже в context)
    //   device   — устройство рендеринга для отправки команд
    // --------------------------------------------------------------------------
    virtual void execute(RenderContext& context,
                         Scene& scene,
                         Camera& camera,
                         RenderDevice& device) = 0;

    // --------------------------------------------------------------------------
    // Завершение прохода.
    // Вызывается после execute(). Может восстанавливать состояния, завершать
    // работу с Framebuffer, выполнять пост-обработку.
    // --------------------------------------------------------------------------
    virtual void end(RenderContext& context, RenderDevice* device = nullptr) {
        (void)context;
        (void)device;
    }

protected:
    RenderPass() = default;
};

} // namespace Rendering
} // namespace MirEngine