// MirEngine/Rendering/Renderer.h
// =================================================================================
// Абстрактный интерфейс высокоуровневого рендерера.
//
// Определяет контракт для выполнения полного цикла рендеринга сцены.
// Конкретные реализации (OpenGLRenderer, MetalRenderer, VulkanRenderer) управляют
// внутренними проходами (GeometryPass, GridPass, SelectionPass и т.д.) и вызывают
// соответствующие методы RenderDevice.
//
// Архитектура:
//   Viewport (управляет областью вывода и камерой)
//       |
//       v
//   Renderer (этот интерфейс)
//       |
//       +--- OpenGLRenderer
//       +--- MetalRenderer   (будущее)
//       +--- VulkanRenderer  (будущее)
//
// Жизненный цикл:
//   1. Создать конкретный экземпляр, передав ему RenderDevice и ресурсы.
//   2. Вызвать initialize() для подготовки проходов и начальных состояний.
//   3. При изменении размера вызвать resize().
//   4. Каждый кадр вызывать render() с указанием сцены и камеры.
//       - Внутри render() выполняет все проходы, используя RenderContext.
//       - Может вызывать beginFrame/endFrame для синхронизации.
//   5. При завершении удалить рендерер (освобождает проходы и временные ресурсы).
// =================================================================================

#pragma once

#include <cstdint>

namespace MirEngine {

// Предварительные объявления (чтобы не тянуть тяжёлые заголовки)
class Scene;
class Camera;

namespace Rendering {

class RenderDevice;
class RenderContext;

class Renderer {
public:
    virtual ~Renderer() = default;

    // --------------------------------------------------------------------------
    // Инициализация рендерера.
    // Должна быть вызвана после создания RenderDevice и загрузки ресурсов.
    // Готовит проходы (GeometryPass, GridPass и т.д.), предварительно компилирует
    // шейдеры, выделяет буферы для пост-обработки.
    // Возвращает true при успехе.
    // --------------------------------------------------------------------------
    virtual bool initialize() = 0;

    // --------------------------------------------------------------------------
    // Основной метод рендеринга одного кадра.
    // Принимает ссылки на сцену и камеру, а также указатель на RenderContext,
    // который уже должен быть заполнен актуальными матрицами и размерами.
    // Внутри вызывает последовательность проходов (GeometryPass, SelectionPass,
    // GridPass, GizmoPass и т.д.), передавая им контекст и сцену.
    // --------------------------------------------------------------------------
    virtual void render(Scene& scene, Camera& camera, RenderContext& context) = 0;

    // --------------------------------------------------------------------------
    // Обновление размеров области рендеринга.
    // Вызывается при изменении размеров окна для перестроения зависимых ресурсов
    // (например, буферов кадра, матриц проекции).
    // --------------------------------------------------------------------------
    virtual void resize(uint32_t width, uint32_t height) = 0;

protected:
    Renderer() = default;
};

} // namespace Rendering
} // namespace MirEngine