// MirUI/Schema/LayoutSchema.hpp
// 📐 Схема компоновки MirUI — реестр всех стандартных типов компоновки (layout).
//
// В MirUI виджеты-контейнеры (Panel, DockPanel, Toolbar, Window) могут
// располагать своих детей по разным правилам: вертикально, горизонтально,
// сеткой, с абсолютным позиционированием, стыковкой к краям.
// Тип компоновки определяет, как LayoutEngine рассчитает размеры и позиции
// дочерних виджетов.
//
// LayoutSchema решает несколько важных задач:
//   1. Определяет перечень всех встроенных типов компоновки с их идентификаторами,
//      названиями, описаниями и иконками для визуального редактора.
//   2. Служит контрактом между ядром и Designer: когда пользователь настраивает
//      контейнер через инспектор, выпадающий список «Тип компоновки» формируется
//      именно из этой схемы. При выборе типа меняется свойство "layout" виджета,
//      и LayoutEngine перестраивает внутренности.
//   3. Позволяет плагинам регистрировать свои типы компоновки (например, «Flow»,
//      «Wrap») и автоматически получать поддержку в редакторе.
//   4. Упрощает локализацию: все строки названий и описаний лежат в одном месте.
//
// Каждый LayoutDescriptor описывает:
//   • id          — строковый идентификатор (например, "vertical", "grid")
//   • name        — короткое имя на русском («Вертикальная», «Сетка»)
//   • description — подробное описание (тултип)
//   • icon        — идентификатор иконки для панели инструментов
//   • defaultSpacing, defaultPadding — типовые значения отступов,
//     которые могут быть использованы как начальные при создании контейнера.
//
// Чистый C++23, без платформенных зависимостей.

#pragma once

#include <string>
#include <vector>
#include <algorithm>

namespace MirUI {

// ── Дескриптор одного типа компоновки ──────────────────────
struct LayoutDescriptor {
    std::string id;           // уникальный идентификатор (например, "vertical", "horizontal")
    std::string name;         // отображаемое имя на русском («Вертикальная»)
    std::string description;  // описание («Дети располагаются друг под другом»)
    std::string icon;         // иконка (платформонезависимая строка, как "layout_vertical")
    double defaultSpacing = 4.0;   // типовой межэлементный отступ по умолчанию
    double defaultPadding = 8.0;   // типовой внутренний отступ контейнера по умолчанию
};

// ── Схема (реестр) типов компоновки ────────────────────────
class LayoutSchema {
public:
    // Получить полный список всех зарегистрированных типов компоновки.
    [[nodiscard]] static const std::vector<LayoutDescriptor>& allLayouts() {
        return layouts();
    }

    // Найти тип компоновки по строковому идентификатору.
    // Возвращает указатель на дескриптор или nullptr, если не найдено.
    [[nodiscard]] static const LayoutDescriptor* find(const std::string& id) {
        auto& lst = layouts();
        auto it = std::find_if(lst.begin(), lst.end(),
            [&id](const LayoutDescriptor& desc) { return desc.id == id; });
        return (it != lst.end()) ? &(*it) : nullptr;
    }

    // Получить список всех идентификаторов (для выпадающих списков).
    [[nodiscard]] static std::vector<std::string> allIds() {
        std::vector<std::string> ids;
        for (const auto& desc : layouts()) {
            ids.push_back(desc.id);
        }
        return ids;
    }

private:
    // Статический реестр всех встроенных типов компоновки.
    static std::vector<LayoutDescriptor>& layouts() {
        static std::vector<LayoutDescriptor> s_layouts = {
            {
                "vertical",
                "Вертикальная",
                "Дочерние виджеты располагаются друг под другом (сверху вниз)",
                "layout_vertical",
                4.0,   // spacing по умолчанию
                8.0    // padding по умолчанию
            },
            {
                "horizontal",
                "Горизонтальная",
                "Дочерние виджеты располагаются рядом (слева направо)",
                "layout_horizontal",
                4.0,
                8.0
            },
            {
                "grid",
                "Сетка",
                "Виджеты выравниваются по ячейкам таблицы с заданным числом столбцов",
                "layout_grid",
                4.0,
                8.0
            },
            {
                "stack",
                "Стек",
                "Виджеты накладываются друг на друга (как страницы книги)",
                "layout_stack",
                0.0,
                0.0
            },
            {
                "dock",
                "Стыковка (Dock)",
                "Виджеты прикрепляются к краям контейнера: слева, справа, сверху, снизу или заполняют центр",
                "layout_dock",
                0.0,
                0.0
            },
            {
                "absolute",
                "Абсолютное позиционирование",
                "Виджеты располагаются по фиксированным координатам (x, y) относительно родителя",
                "layout_absolute",
                0.0,
                0.0
            }
        };
        return s_layouts;
    }
};

} // namespace MirUI