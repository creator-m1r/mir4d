// MirUI/Renderers/PlatformAdapter.hpp
// 🌉 Базовый адаптер платформы — связывает MirUI Core с конкретной ОС (macOS, Windows, Linux).
//
// Каждый платформенный рендерер (SwiftUI, WinUI, WebUI) наследуется от этого
// абстрактного класса и реализует несколько ключевых методов.
// PlatformAdapter решает три главные задачи:
//   1. Управление окнами (создание, закрытие, установка заголовка и размеров).
//   2. Присоединение корневого виджета MirUI к платформенному окну.
//      Адаптер получает UIDocument, извлекает WidgetTree и «переводит»
//      каждое C++-описание виджета в нативный UI-элемент (NSView, HWND, HTML-элемент).
//   3. Запуск главного цикла обработки событий (run loop).
//      В этом цикле адаптер слушает системные события (мышь, клавиатура, изменения размеров),
//      преобразует их в MirUI::Event и отправляет в EventDispatcher документа.
//      EventDispatcher доставляет события виджетам, а те могут вызывать команды
//      через CommandBus. После обработки адаптер перерисовывает изменившиеся виджеты.
//
// Таким образом, весь UI-фреймворк работает как замкнутая система:
//   Системное событие → MirUI Event → EventDispatcher → Widget → CommandBus
//   → изменение WidgetTree → Renderer обновляет нативные элементы.
//
// PlatformAdapter НЕ содержит конкретного кода SwiftUI или WinUI —
// он только задаёт интерфейс, который должны реализовать наследники.
// Благодаря этому ядро MirUI остаётся полностью независимым от платформы.
//
// Чистый C++23 (интерфейс), без платформенных зависимостей.

#pragma once

#include "../Designer/Document/UIDocument.hpp"
#include "../Core/Events/EventDispatcher.hpp"
#include <string>
#include <memory>

namespace MirUI {

class PlatformAdapter {
public:
    virtual ~PlatformAdapter() = default;

    // ── Управление окнами ────────────────────────────────────
    // Создать окно с заданными параметрами (размер, заголовок, стиль).
    // Возвращает идентификатор окна (в рамках адаптера), или 0 при ошибке.
    // По умолчанию реализация-заглушка ничего не делает.
    virtual uint64_t createWindow(const std::string& title, double width, double height) {
        (void)title; (void)width; (void)height;
        return 0; // нет окна
    }

    // Закрыть окно по идентификатору.
    virtual void closeWindow(uint64_t windowId) {
        (void)windowId;
    }

    // ── Привязка документа ───────────────────────────────────
    // Связать окно с документом MirUI. После вызова этого метода адаптер
    // должен начать отображать дерево виджетов из документа в указанном окне.
    // Любые изменения в документе (через команды) должны вызывать обновление UI.
    virtual void attachDocument(uint64_t windowId, UIDocument& document) {
        (void)windowId; (void)document;
    }

    // Отвязать документ от окна (например, перед закрытием).
    virtual void detachDocument(uint64_t windowId) {
        (void)windowId;
    }

    // ── Главный цикл ─────────────────────────────────────────
    // Запускает цикл обработки событий. Должен блокировать вызывающий поток
    // до тех пор, пока все окна не будут закрыты. Реализация по умолчанию —
    // немедленный выход (для тестов, где нет окон).
    virtual void run() {
        // По умолчанию ничего не делаем — тестовый режим.
    }

    // ── Обновление отображения ───────────────────────────────
    // Сообщает адаптеру, что документ изменился и нужно перерисовать
    // конкретный виджет или всё окно. Реализация может быть асинхронной
    // (поставить запрос на перерисовку в очередь главного потока).
    virtual void requestUpdate(uint64_t windowId) {
        (void)windowId;
    }

    // ── Диспетчер событий ────────────────────────────────────
    // Каждый адаптер имеет свой экземпляр EventDispatcher, который
    // будет получать преобразованные системные события и доставлять их виджетам.
    // Наследники должны использовать этот диспетчер для отправки событий.
    [[nodiscard]] EventDispatcher& eventDispatcher() { return m_eventDispatcher; }
    [[nodiscard]] const EventDispatcher& eventDispatcher() const { return m_eventDispatcher; }

protected:
    EventDispatcher m_eventDispatcher; // Общий для всех окон адаптера.
};

} // namespace MirUI