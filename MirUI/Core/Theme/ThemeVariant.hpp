// MirUI/Core/Theme/ThemeVariant.hpp
// 🎭 Вариант темы — определяет базовый визуальный режим (светлый, тёмный, контрастный).
//
// Каждая зарегистрированная тема имеет поле variant, которое указывает,
// к какой категории она относится. Это позволяет системе автоматически
// подбирать подходящую тему (например, переключаться между светлой и тёмной
// по системным настройкам macOS/Windows).
//
// Значения:
//   • Light         — светлая тема (светлый фон, тёмный текст).
//   • Dark          — тёмная тема (тёмный фон, светлый текст).
//   • HighContrast  — тема с повышенной контрастностью для слабовидящих.
//   • Custom        — пользовательская тема, не попадающая в стандартные категории.
//
// Чистый C++23, без платформенных зависимостей.

#pragma once

namespace MirUI {

enum class ThemeVariant {
    Light,
    Dark,
    HighContrast,
    Custom
};

} // namespace MirUI
