// MirUI/Core/Widget/PropertyType.hpp
// 🏷️ Типы свойств виджета для инспектора и редактора.
// Определяет, какого рода значение хранится в свойстве: строка, число, цвет, шрифт и т.д.
// Используется в PropertyDescriptor и схемах для автоматической генерации редакторов.
// Чистый C++23, без платформенных зависимостей.

#pragma once

namespace MirUI {

enum class PropertyType {
    Boolean,   // true/false — отображается как переключатель (галочка)
    Integer,   // целое число (int64_t)
    Number,    // дробное число (double)
    String,    // произвольный текст
    Color,     // цвет в формате "#RRGGBBAA" (строка)
    Font,      // шрифт в формате "family;size;weight;style" (строка)
    Point,     // координаты x,y (пока не реализовано как составной тип)
    Size,      // размеры width,height (пока не реализовано)
    Rect,      // прямоугольник (пока не реализовано)
    Insets,    // отступы (пока не реализовано)
    Enum       // выбор из фиксированного списка строк (std::string)
};

} // namespace MirUI