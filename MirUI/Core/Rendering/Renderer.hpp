// MirUI/Core/Rendering/Renderer.hpp
// Абстрактный интерфейс рендерера — основа для всех платформенных адаптеров.
// Описывает, что должен уметь любой рендерер, но не содержит
// конкретной графической реализации (ни OpenGL, ни SwiftUI, ни WinUI).
// Чистый C++23, без платформенных зависимостей.

#pragma once

#include "../Widget/WidgetTree.hpp"

namespace MirUI {

class Renderer {
public:
    // Виртуальный деструктор — обязателен для полиморфных классов.
    virtual ~Renderer() = default;

    // Вызывается один раз перед началом отрисовки кадра.
    // Здесь можно подготовить ресурсы, очистить буферы и т.д.
    virtual void beginFrame() {}

    // Главный метод: отрисовать всё дерево виджетов.
    // Каждый конкретный рендерер (SwiftUI, WinUI, NullRenderer) сам решает,
    // как обойти дерево и как отобразить каждый виджет.
    virtual void render(WidgetTree& tree) = 0;

    // Вызывается после завершения отрисовки кадра.
    // Здесь можно завершить команды, поменять буферы и т.д.
    virtual void endFrame() {}
};

} // namespace MirUI