// MirUI/Core/Layout/Unit.hpp
// 📏 Единицы измерения для размеров виджетов.
// Определяет, как интерпретировать числовое значение ширины или высоты:
//   • Pixel  — абсолютная величина в логических пикселях (как точки на экране)
//   • Percent — процент от размера родительского виджета
//   • Auto   — размер определяется автоматически: по содержимому (Fit) или заполнением (Fill)
//
// Используется в LayoutData для задания предпочтений компоновки.
// Чистый C++23, без платформенных зависимостей.

#pragma once

namespace MirUI {

enum class Unit {
    Pixel,   // фиксированное количество пикселей (например, ширина = 200 px)
    Percent, // доля от родителя (например, ширина = 50% — половина родителя)
    Auto     // автоматический расчёт (растянуть или подстроить под содержимое)
};

} // namespace MirUI