// MirUI/Designer/Preview/PreviewMode.hpp
// 🔄 Режим предпросмотра для MirUI Designer.
//
// Определяет два основных состояния редактора:
//   • Edit    – обычный режим редактирования (видны направляющие, ручки, сетка)
//   • Preview – предпросмотр, при котором интерфейс выглядит как в реальном приложении
//
// Используется PreviewManager, DesignerCanvas и другими компонентами,
// чтобы синхронизировать своё поведение (например, холст отключает
// перетаскивание и выделение в режиме Preview).
//
// Чистый C++23, без платформенных зависимостей.

#pragma once

namespace MirUI {

enum class PreviewMode {
    Edit,     // обычный режим редактирования
    Preview   // предпросмотр (без вспомогательных элементов)
};

} // namespace MirUI