// Дизайнер просто использует этот готовый класс. Этот файл нужен для того,
// чтобы структура папок отражала логическую принадлежность: всё, что связано
// с выделением в контексте дизайнера, лежит в папке Designer/Selection.
// Но реализация — одна на всех, она находится в Core.
//
// Чистый C++23, без платформенных зависимостей.

